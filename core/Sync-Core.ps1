param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$coreDir = $PSScriptRoot
$headerPath = Join-Path $coreDir 'keycat_core.h'
$sourcePath = Join-Path $coreDir 'keycat_core.c'
$targetPath = [IO.Path]::GetFullPath((Join-Path $coreDir '..\windows\app\KeycatCore.g.cs'))

$headerText = [IO.File]::ReadAllText($headerPath, [Text.Encoding]::UTF8)
$sourceText = [IO.File]::ReadAllText($sourcePath, [Text.Encoding]::UTF8)

$translatorCode = @'
using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

public static class CoreTranslator
{
    private static readonly Dictionary<string, string> MathMap = new Dictionary<string, string>
    {
        { "sqrt", "Math.Sqrt" },
        { "fabs", "Math.Abs" },
        { "fmin", "Math.Min" },
        { "fmax", "Math.Max" },
        { "sin", "Math.Sin" },
        { "cos", "Math.Cos" },
        { "tanh", "Math.Tanh" },
        { "exp", "Math.Exp" },
        { "floor", "Math.Floor" }
    };

    private static readonly HashSet<string> ValueStructs = new HashSet<string>
    {
        "KCPoint", "KCHeadPose", "KCOfficeArmGeometry", "KCOfficeBodyPose", "KCCapLayout", "KCCatMotion", "KCImpactLayout"
    };

    private static readonly HashSet<string> PoseConstants = new HashSet<string>
    {
        "KC_POSE_IDLE", "KC_POSE_WORKING", "KC_POSE_HOVER", "KC_POSE_CLICK", "KC_POSE_SLEEPING"
    };

    private enum TokenKind { Word, Number, String, Op, Punct }

    private sealed class Token
    {
        public TokenKind Kind;
        public string Text;
        public int Line;
    }

    private static List<Token> Tokenize(string code)
    {
        var tokens = new List<Token>();
        int i = 0, line = 1;
        while (i < code.Length)
        {
            char c = code[i];
            if (c == '\n') { line++; i++; continue; }
            if (char.IsWhiteSpace(c)) { i++; continue; }
            if (c == '/' && i + 1 < code.Length && code[i + 1] == '/')
            {
                while (i < code.Length && code[i] != '\n') i++;
                continue;
            }
            if (c == '/' && i + 1 < code.Length && code[i + 1] == '*')
            {
                i += 2;
                while (i + 1 < code.Length && !(code[i] == '*' && code[i + 1] == '/'))
                {
                    if (code[i] == '\n') line++;
                    i++;
                }
                i += 2;
                continue;
            }
            if (c == '"')
            {
                int start = i++;
                while (i < code.Length && code[i] != '"')
                {
                    if (code[i] == '\\' && i + 1 < code.Length) i++;
                    i++;
                }
                i++;
                tokens.Add(new Token { Kind = TokenKind.String, Text = code.Substring(start, i - start), Line = line });
                continue;
            }
            if (char.IsLetter(c) || c == '_')
            {
                int start = i++;
                while (i < code.Length && (char.IsLetterOrDigit(code[i]) || code[i] == '_')) i++;
                tokens.Add(new Token { Kind = TokenKind.Word, Text = code.Substring(start, i - start), Line = line });
                continue;
            }
            if (char.IsDigit(c) || (c == '.' && i + 1 < code.Length && char.IsDigit(code[i + 1])))
            {
                int start = i++;
                while (i < code.Length && (char.IsLetterOrDigit(code[i]) || code[i] == '.')) i++;
                tokens.Add(new Token { Kind = TokenKind.Number, Text = code.Substring(start, i - start), Line = line });
                continue;
            }
            if (i + 1 < code.Length)
            {
                string two = code.Substring(i, 2);
                if (two == "->" || two == "==" || two == "!=" || two == "<=" || two == ">=" ||
                    two == "&&" || two == "||" || two == "++" || two == "--" ||
                    two == "+=" || two == "-=" || two == "*=" || two == "/=")
                {
                    tokens.Add(new Token { Kind = TokenKind.Op, Text = two, Line = line });
                    i += 2;
                    continue;
                }
            }
            tokens.Add(new Token { Kind = "{};(),[]".IndexOf(c) >= 0 ? TokenKind.Punct : TokenKind.Op, Text = c.ToString(), Line = line });
            i++;
        }
        return tokens;
    }

    public static string Generate(string header, string source)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated from core/keycat_core.h and core/keycat_core.c by core/Sync-Core.ps1.");
        sb.AppendLine("// Do not edit this file directly.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine();

        foreach (Match m in Regex.Matches(header, @"typedef\s+enum\s*\{([^}]*)\}\s*(\w+)\s*;"))
        {
            sb.AppendFormat("internal enum {0}", m.Groups[2].Value).AppendLine();
            sb.AppendLine("{");
            foreach (string rawItem in m.Groups[1].Value.Split(','))
            {
                string item = rawItem.Trim();
                if (item.Length > 0) sb.AppendLine("    " + item + ",");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        foreach (Match m in Regex.Matches(header, @"typedef\s+struct\s*\{([^}]*)\}\s*(\w+)\s*;"))
        {
            string body = m.Groups[1].Value;
            string name = m.Groups[2].Value;
            bool isClass = name == "KCSceneState";
            sb.AppendFormat("internal {0} {1}", isClass ? "sealed class" : "struct", name).AppendLine();
            sb.AppendLine("{");
            foreach (string rawLine in body.Split(';'))
            {
                string decl = rawLine.Trim();
                if (decl.Length == 0) continue;
                Match arr = Regex.Match(decl, @"^(\w+)\s+(\w+)\[(\d+)\]$");
                if (arr.Success)
                {
                    sb.AppendFormat("    public {0}[] {1} = new {0}[{2}];",
                        arr.Groups[1].Value, arr.Groups[2].Value, arr.Groups[3].Value).AppendLine();
                    continue;
                }
                Match field = Regex.Match(decl, @"^(\w+)\s+(.+)$");
                if (field.Success)
                {
                    sb.AppendFormat("    public {0} {1};", field.Groups[1].Value, field.Groups[2].Value.Trim()).AppendLine();
                }
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("internal static partial class KeycatCore");
        sb.AppendLine("{");

        foreach (Match m in Regex.Matches(header, @"^\s*#define\s+(KC_\w+)\s+""([^""]*)""", RegexOptions.Multiline))
        {
            sb.AppendFormat("    public const string {0} = \"{1}\";", m.Groups[1].Value, m.Groups[2].Value).AppendLine();
        }

        Match anonEnum = Regex.Match(header, @"\benum\s*\{([^}]*)\}\s*;");
        if (anonEnum.Success)
        {
            foreach (string rawItem in anonEnum.Groups[1].Value.Split(','))
            {
                string item = rawItem.Trim();
                if (item.Length == 0) continue;
                sb.AppendFormat("    public const int {0};", item).AppendLine();
            }
        }
        sb.AppendLine();

        string cleanedSource = Regex.Replace(source, @"^\s*#.*$", "", RegexOptions.Multiline);
        List<Token> tokens = Tokenize(cleanedSource);
        int idx = 0;
        while (idx < tokens.Count)
        {
            bool isStatic = false;
            if (tokens[idx].Text == "static") { isStatic = true; idx++; }
            string retType = tokens[idx++].Text;
            string fnName = tokens[idx++].Text;
            if (tokens[idx++].Text != "(") throw new InvalidOperationException("Expected '(' after " + fnName);

            var paramParts = new List<string>();
            while (tokens[idx].Text != ")")
            {
                if (tokens[idx].Text == ",") { idx++; continue; }
                if (tokens[idx].Text == "const") idx++;
                string pType = tokens[idx++].Text;
                if (tokens[idx].Text == "*") idx++;
                string pName = tokens[idx++].Text;
                paramParts.Add(pType + " " + pName);
            }
            idx++; // ')'
            if (tokens[idx].Text != "{") throw new InvalidOperationException("Expected '{' for " + fnName);

            int bodyStart = idx;
            int depth = 0;
            do
            {
                if (tokens[idx].Text == "{") depth++;
                else if (tokens[idx].Text == "}") depth--;
                idx++;
            } while (depth > 0 && idx < tokens.Count);
            int bodyEnd = idx;

            sb.AppendFormat("    {0} static {1} {2}({3})",
                isStatic ? "private" : "public",
                retType,
                fnName,
                string.Join(", ", paramParts.ToArray())).AppendLine();

            EmitBody(sb, tokens, bodyStart, bodyEnd);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static void EmitBody(StringBuilder sb, List<Token> tokens, int start, int end)
    {
        int indent = 1;
        bool atLineStart = true;
        int parenDepth = 0;
        for (int i = start; i < end; i++)
        {
            Token t = tokens[i];
            if (t.Text == "}")
            {
                indent--;
                if (!atLineStart) sb.AppendLine();
                sb.Append(' ', indent * 4).Append('}').AppendLine();
                atLineStart = true;
                continue;
            }
            if (t.Text == "{")
            {
                if (!atLineStart) sb.Append(' ');
                else sb.Append(' ', indent * 4);
                sb.Append('{').AppendLine();
                indent++;
                atLineStart = true;
                continue;
            }
            if (atLineStart)
            {
                sb.Append(' ', indent * 4);
                atLineStart = false;
            }

            // Local value-struct declaration: `KCPoint r;` -> `KCPoint r = new KCPoint();`
            if (ValueStructs.Contains(t.Text) && i + 2 < end &&
                tokens[i + 1].Kind == TokenKind.Word && tokens[i + 2].Text == ";")
            {
                sb.AppendFormat("{0} {1} = new {0}();", t.Text, tokens[i + 1].Text).AppendLine();
                i += 2;
                atLineStart = true;
                continue;
            }

            string text = t.Text;
            if (text == "->") text = ".";
            else if (t.Kind == TokenKind.Word && MathMap.ContainsKey(text)) text = MathMap[text];
            else if (t.Kind == TokenKind.Word && PoseConstants.Contains(text)) text = "(int)KCOfficePose." + text;

            if (text == "(") parenDepth++;
            else if (text == ")") parenDepth = Math.Max(0, parenDepth - 1);

            if (text == ";")
            {
                sb.Append(';');
                if (parenDepth == 0)
                {
                    sb.AppendLine();
                    atLineStart = true;
                }
                else
                {
                    sb.Append(' ');
                }
                continue;
            }

            bool needSpaceBefore = ShouldSpaceBefore(tokens, i, start, text);
            if (needSpaceBefore && sb.Length > 0 && sb[sb.Length - 1] != ' ' && sb[sb.Length - 1] != '\n')
                sb.Append(' ');
            sb.Append(text);
        }
    }

    private static bool ShouldSpaceBefore(List<Token> tokens, int i, int start, string current)
    {
        if (i <= start) return false;
        string prev = tokens[i - 1].Text;
        if (prev == "{" || prev == "(" || prev == "[" || prev == "." || prev == "->" || prev == "!") return false;
        if (current == "," || current == ";" || current == ")" || current == "]" || current == "." || current == "->") return false;
        if (current == "(" && tokens[i - 1].Kind == TokenKind.Word &&
            prev != "if" && prev != "for" && prev != "while" && prev != "return") return false;
        if (prev == "-" && (i - 2 < start || IsPrefixContext(tokens[i - 2].Text))) return false;
        if ((current == "++" || current == "--") && tokens[i - 1].Kind == TokenKind.Word) return false;
        return true;
    }

    private static bool IsPrefixContext(string prev)
    {
        return prev == "=" || prev == "(" || prev == "," || prev == "?" || prev == ":" ||
               prev == "return" || prev == "<" || prev == ">" || prev == "<=" || prev == ">=" ||
               prev == "==" || prev == "!=" || prev == "&&" || prev == "||" || prev == "+" ||
               prev == "-" || prev == "*" || prev == "/";
    }
}
'@

if (-not ('CoreTranslator' -as [type])) {
    Add-Type -TypeDefinition $translatorCode -Language CSharp
}

$generated = [CoreTranslator]::Generate($headerText, $sourceText)
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

if ($Check) {
    if (-not (Test-Path -LiteralPath $targetPath -PathType Leaf)) {
        throw "Generated core file is missing: $targetPath"
    }
    $existing = [IO.File]::ReadAllText($targetPath, [Text.Encoding]::UTF8).Replace("`r`n", "`n")
    if ($existing -ne $generated) {
        throw "windows/app/KeycatCore.g.cs is out of sync with core/keycat_core.h/.c. Run core\Sync-Core.ps1."
    }
    Write-Output 'PASS: windows/app/KeycatCore.g.cs is in sync with core/.'
} else {
    [IO.File]::WriteAllText($targetPath, $generated, $utf8NoBom)
    Write-Output "Generated $targetPath"
}
